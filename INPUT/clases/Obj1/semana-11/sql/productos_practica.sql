-- 3.1 / 3.2  Crear la tabla con el esquema compartido
create table if not exists public.productos_practica (
  id          int8 generated by default as identity primary key,  -- autoincremental
  created_at  timestamptz not null default now(),
  nombre      text,
  descripcion text,
  precio      int8,
  unidades    int8,
  descuento   float8,
  disponible  bool,
  categorias  json
);

