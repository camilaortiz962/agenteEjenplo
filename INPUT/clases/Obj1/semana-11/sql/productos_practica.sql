-- 3.4  Row Level Security — OPCIÓN B (RLS activo + política abierta)
-- ⚠️ Temporal: cualquiera con tu anon key puede leer/escribir/borrar.
--    En la semana 13 se reemplaza por reglas reales con Supabase Auth.
alter table public.productos_practica enable row level security;

create policy "Enable read/write access for all users"
  on public.productos_practica
